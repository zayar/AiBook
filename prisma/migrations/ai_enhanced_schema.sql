-- Business Intelligence Cache for performance
CREATE TABLE bi_cache (
    id VARCHAR(255) PRIMARY KEY,
    tenant_id VARCHAR(255) NOT NULL,
    cache_key VARCHAR(500) NOT NULL,
    query_hash VARCHAR(255) NOT NULL,
    
    -- Cached Data
    result JSON NOT NULL,
    metadata JSON,
    
    -- Cache Management
    expires_at TIMESTAMP NOT NULL,
    hit_count INTEGER DEFAULT 0,
    last_accessed TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
    
    UNIQUE KEY unique_tenant_cache (tenant_id, cache_key),
    INDEX idx_bi_cache_tenant (tenant_id),
    INDEX idx_bi_cache_expires (expires_at),
    INDEX idx_bi_cache_hash (tenant_id, query_hash)
);

-- AI Model Registry
CREATE TABLE ai_model_registry (
    id VARCHAR(255) PRIMARY KEY,
    tenant_id VARCHAR(255) NOT NULL,
    
    -- Model Information
    model_name VARCHAR(255) NOT NULL,
    model_type VARCHAR(255) NOT NULL,
    version VARCHAR(50) NOT NULL,
    
    -- Model Configuration
    parameters JSON NOT NULL,
    features JSON NOT NULL,
    
    -- Performance Metrics
    accuracy FLOAT,
    precision_score FLOAT,
    recall_score FLOAT,
    f1_score FLOAT,
    
    -- Deployment Status
    status VARCHAR(50) DEFAULT 'training', -- training, active, deprecated
    deployed_at TIMESTAMP NULL,
    last_trained TIMESTAMP NULL,
    
    -- Model Artifacts
    model_path VARCHAR(500),
    artifacts JSON,
    
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
    
    INDEX idx_model_registry_tenant (tenant_id),
    INDEX idx_model_registry_type (tenant_id, model_type),
    INDEX idx_model_registry_status (tenant_id, status),
    INDEX idx_model_registry_version (tenant_id, model_name, version)
);