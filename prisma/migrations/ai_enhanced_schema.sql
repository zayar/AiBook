-- AI Conversation History for learning
CREATE TABLE ai_conversation_history (
    id VARCHAR(255) PRIMARY KEY,
    tenant_id VARCHAR(255) NOT NULL,
    session_id VARCHAR(255) NOT NULL,
    user_id VARCHAR(255),
    
    -- Conversation Data
    query TEXT NOT NULL,
    intent VARCHAR(255),
    entities JSON,
    response JSON NOT NULL,
    confidence FLOAT NOT NULL,
    
    -- Performance Tracking
    execution_time INTEGER, -- milliseconds
    feedback VARCHAR(50), -- positive, negative, neutral
    user_rating INTEGER, -- 1-5 scale
    
    -- Learning Data
    correction_applied BOOLEAN DEFAULT FALSE,
    correction_details JSON,
    
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
    
    INDEX idx_conversation_tenant (tenant_id),
    INDEX idx_conversation_session (tenant_id, session_id),
    INDEX idx_conversation_intent (tenant_id, intent),
    INDEX idx_conversation_feedback (tenant_id, feedback),
    INDEX idx_conversation_created (tenant_id, created_at)
);

