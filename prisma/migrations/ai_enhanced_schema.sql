-- AI-Enhanced Schema Migration
-- This migration adds AI-specific tables and enhances existing ones for intelligent financial analysis

-- Add new enum types
CREATE TYPE automation_level AS ENUM ('MANUAL', 'AI_SUGGESTED', 'AI_AUTOMATED', 'AI_LEARNED');
CREATE TYPE insight_type AS ENUM ('OPPORTUNITY', 'RISK', 'OPTIMIZATION', 'PREDICTION', 'ANOMALY', 'BENCHMARK');
CREATE TYPE insight_priority AS ENUM ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW');

-- Business Context table for rich AI metadata
CREATE TABLE business_context (
    id VARCHAR(255) PRIMARY KEY,
    entry_id VARCHAR(255) UNIQUE NOT NULL,
    tenant_id VARCHAR(255) NOT NULL,
    
    -- Business Dimensions
    business_unit VARCHAR(255),
    project VARCHAR(255),
    campaign VARCHAR(255),
    channel VARCHAR(255),
    territory VARCHAR(255),
    
    -- Customer/Vendor Intelligence
    entity_segment VARCHAR(255),
    entity_tier VARCHAR(255),
    relationship_length INTEGER,
    lifetime_value DECIMAL(15,2),
    payment_history JSON,
    risk_profile VARCHAR(255),
    
    -- Contextual Metadata
    market_conditions JSON,
    competitor_analysis JSON,
    seasonal_factors JSON,
    external_events JSON,
    
    -- AI Learning Data
    user_decision_patterns JSON,
    correction_history JSON,
    prediction_accuracy JSON,
    
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    FOREIGN KEY (entry_id) REFERENCES entries(id) ON DELETE CASCADE,
    FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
    
    INDEX idx_business_context_tenant (tenant_id),
    INDEX idx_business_context_segment (tenant_id, entity_segment),
    INDEX idx_business_context_business_unit (tenant_id, business_unit),
    INDEX idx_business_context_composite (tenant_id, entity_segment, business_unit, created_at)
);

-- AI Model Performance tracking
CREATE TABLE ai_model_performance (
    id VARCHAR(255) PRIMARY KEY,
    model_type VARCHAR(255) NOT NULL,
    tenant_id VARCHAR(255) NOT NULL,
    
    -- Performance Metrics
    accuracy FLOAT,
    precision_score FLOAT,
    recall_score FLOAT,
    f1_score FLOAT,
    
    -- Business Metrics
    times_saved INTEGER DEFAULT 0,
    errors_detected INTEGER DEFAULT 0,
    revenue_impact DECIMAL(15,2),
    
    -- Learning Progression
    training_data_points INTEGER,
    last_training_date TIMESTAMP,
    improvement_rate FLOAT,
    
    period TIMESTAMP NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
    
    INDEX idx_ai_performance_tenant (tenant_id),
    INDEX idx_ai_performance_model (tenant_id, model_type),
    INDEX idx_ai_performance_period (tenant_id, period)
);

-- Business Insights generated by AI
CREATE TABLE business_insights (
    id VARCHAR(255) PRIMARY KEY,
    tenant_id VARCHAR(255) NOT NULL,
    
    -- Insight Classification
    type insight_type NOT NULL,
    category VARCHAR(255) NOT NULL,
    priority insight_priority NOT NULL,
    confidence FLOAT NOT NULL,
    
    -- Insight Content
    title VARCHAR(500) NOT NULL,
    description TEXT,
    actionable BOOLEAN DEFAULT FALSE,
    recommendations JSON,
    
    -- Impact Analysis
    potential_impact DECIMAL(15,2),
    timeframe VARCHAR(255),
    effort VARCHAR(255),
    
    -- Data Sources
    data_points JSON,
    related_entities JSON,
    
    -- User Interaction
    viewed BOOLEAN DEFAULT FALSE,
    viewed_at TIMESTAMP NULL,
    action_taken VARCHAR(255),
    user_feedback JSON,
    
    -- Lifecycle
    is_active BOOLEAN DEFAULT TRUE,
    expires_at TIMESTAMP NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
    
    INDEX idx_business_insights_tenant (tenant_id),
    INDEX idx_business_insights_type (tenant_id, type),
    INDEX idx_business_insights_priority (tenant_id, priority),
    INDEX idx_business_insights_active (tenant_id, is_active),
    INDEX idx_business_insights_created (tenant_id, created_at)
);

-- Financial KPIs with AI predictions
CREATE TABLE financial_kpis (
    id VARCHAR(255) PRIMARY KEY,
    tenant_id VARCHAR(255) NOT NULL,
    
    -- KPI Definition
    name VARCHAR(255) NOT NULL,
    category VARCHAR(255) NOT NULL,
    calculation JSON NOT NULL,
    
    -- Current Values
    current_value DECIMAL(20,8) NOT NULL,
    previous_value DECIMAL(20,8),
    target_value DECIMAL(20,8),
    benchmark_value DECIMAL(20,8),
    
    -- Trends
    trend VARCHAR(50),
    change_percent FLOAT,
    
    -- AI Predictions
    predicted_value DECIMAL(20,8),
    prediction_confidence FLOAT,
    
    period TIMESTAMP NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
    
    INDEX idx_financial_kpis_tenant (tenant_id),
    INDEX idx_financial_kpis_category (tenant_id, category),
    INDEX idx_financial_kpis_period (tenant_id, period),
    INDEX idx_financial_kpis_trends (tenant_id, category, period DESC)
);

